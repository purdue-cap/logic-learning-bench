#!/usr/bin/env python3
"""Generate Delis .sl benchmark files from SyGuS SLIA string-transformation benchmarks.

Converts a SyGuS SLIA file (FlashFill-style string synthesis) into a Delis
finite-model .sl file using the FACET value-checking encoding.

Key idea: all strings (inputs, outputs, constants) are laid out on a single
"tape". The Str semantics checks whether an expression produces tape[lo..hi];
the Int semantics checks whether an expression equals exp_int. Bool semantics
returns Bool directly.

Only 3-ary or smaller interpreted functions are precomputed (char_eq, int_plus,
int_minus, pos_offset, pos_diff, substr_match). The 4-ary+ operations
(prefixof, suffixof, contains, indexof) are expressed directly in the semantics
using substr_match + exists/forall, avoiding O(n^4) table blowup.
"""
import argparse
import re
import sys
from pathlib import Path


# ---------------------------------------------------------------------------
# SyGuS parsing
# ---------------------------------------------------------------------------

def parse_sygus(path: Path):
    text = path.read_text()

    m = re.search(r'\(synth-fun\s+\w+\s*\(((?:\([^)]*\)\s*)*)\)', text)
    if not m:
        raise ValueError(f"no synth-fun in {path}")
    args_str = m.group(1).strip()
    arg_names = re.findall(r'\((\w+)\s+String\)', args_str)
    n_args = len(arg_names)

    m2 = re.search(r'ntString\s+String\s*\(([^)]*(?:\([^)]*\))*[^)]*)\)', text, re.DOTALL)
    constants = []
    if m2:
        grammar_body = m2.group(1)
        for s in re.findall(r'"((?:[^"\\]|\\.)*)"', grammar_body):
            u = unescape_str(s)
            if u not in arg_names:
                constants.append(u)

    constraints = []
    for cm in re.finditer(
        r'\(constraint\s+\(=\s+\(f\s+(.*?)\)\s+"((?:[^"\\]|\\.)*)"\s*\)\s*\)',
        text, re.DOTALL,
    ):
        args_part = cm.group(1)
        out = unescape_str(cm.group(2))
        inputs = [unescape_str(s) for s in re.findall(r'"((?:[^"\\]|\\.)*)"', args_part)]
        constraints.append((inputs, out))

    seen = set()
    deduped = []
    for c in constraints:
        key = (tuple(c[0]), c[1])
        if key not in seen:
            seen.add(key)
            deduped.append(c)

    return n_args, constants, deduped


def unescape_str(s: str) -> str:
    return (s
            .replace('\\\\', '\x00')
            .replace('\\"', '"')
            .replace('\\n', '\n')
            .replace('\\t', '\t')
            .replace('\x00', '\\'))


# ---------------------------------------------------------------------------
# Tape construction
# ---------------------------------------------------------------------------

def build_tape(n_args, constants, constraints):
    ordered = []
    seen = set()

    def add(s):
        if s not in seen:
            seen.add(s)
            ordered.append(s)

    for c in constants:
        add(c)
    for inputs, out in constraints:
        for inp in inputs:
            add(inp)
        add(out)

    tape = "".join(ordered)
    positions = {}
    offset = 0
    for s in ordered:
        positions[s] = (offset, offset + len(s))
        offset += len(s)

    return tape, positions


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------

def si(v):
    if v == 'bot':
        return 'bot'
    if isinstance(v, int):
        return '$neg1' if v == -1 else f'${v}'
    return str(v)


def pos(v):
    return f'${v}' if isinstance(v, int) else str(v)


def pos_name(v, tape_len):
    return '$end' if v == tape_len else f'${v}'


# ---------------------------------------------------------------------------
# Main emission
# ---------------------------------------------------------------------------

def emit(n_args, constants, constraints, tape, positions, max_int):
    tape_len = len(tape)
    out = []

    out.append("; Generated by gen.py — FACET value-checking encoding for SLIA")
    out.append(f"; tape length = {tape_len}, max_int = {max_int}, "
               f"{n_args} args, {len(constants)} consts, {len(constraints)} constraints")
    out.append("(set-logic ALL)")
    out.append("")

    # --- Term types ---
    str_nullaries = [f"(str.c{i})" for i in range(len(constants))]
    for i in range(n_args):
        str_nullaries.append(f"(str.arg{i})")
    str_nary = [
        "(str.++ Str Str)",
        "(str.replace Str Str Str)",
        "(str.at Str SInt)",
        "(str.int2str SInt)",
        "(str.ite SBool Str Str)",
        "(str.substr Str SInt SInt)",
    ]
    int_terms = [
        "(int.0)", "(int.1)", "(int.neg1)",
        "(int.+ SInt SInt)", "(int.- SInt SInt)",
        "(int.len Str)", "(int.to_int Str)",
        "(int.ite SBool SInt SInt)", "(int.indexof Str Str SInt)",
    ]
    bool_terms = [
        "(bool.true)", "(bool.false)",
        "(bool.= SInt SInt)",
        "(bool.prefixof Str Str)", "(bool.suffixof Str Str)",
        "(bool.contains Str Str)",
    ]

    out.append("(declare-term-types")
    out.append(" ((Str 0) (SInt 0) (SBool 0))")
    out.append(" (")
    out.append("   (" + " ".join(str_nullaries + str_nary) + ")")
    out.append("   (" + " ".join(int_terms) + ")")
    out.append("   (" + " ".join(bool_terms) + ")")
    out.append(" )")
    out.append(")")
    out.append("")

    # --- Declarations ---
    out.append("(declare-sort Pos 0)")
    out.append("(declare-sort SymInt 0)")
    out.append("")
    out.append("(declare-fun char_eq (Pos Pos) Bool)")
    out.append("(declare-fun int_plus (SymInt SymInt) SymInt)")
    out.append("(declare-fun int_minus (SymInt SymInt) SymInt)")
    out.append("(declare-fun pos_offset (Pos SymInt) Pos)")
    out.append("(declare-fun pos_diff (Pos Pos) SymInt)")
    out.append("(declare-fun substr_match (Pos Pos SymInt) Bool)")
    out.append("")

    # --- Declarations for per-model 0-ary arg-position functions ---
    for i in range(n_args):
        out.append(f"(declare-fun arg{i}_lo () Pos)")
        out.append(f"(declare-fun arg{i}_hi () Pos)")
    if n_args > 0:
        out.append("")

    # --- Aspect ---
    # lo, hi are Int (0..tape_len) — compiler auto-converts to Pos for function calls.
    # exp_int is SymInt (Univ) because it can hold bot and $neg1.
    # Arg positions are NOT in the aspect — they live in per-model 0-ary interp-fun.
    out.append("(define-finite Str.Asp")
    out.append(f"  (record (model Model) (lo Int) (hi Int) (exp_int SymInt))")
    out.append(f"  :where (and (<= 0 lo) (<= lo hi) (<= hi {tape_len})))")
    out.append("")

    # --- Aspect builder helper ---
    def asp(**ov):
        fields = ["(model asp)"]
        fields.append(ov.get("lo", "(lo asp)"))
        fields.append(ov.get("hi", "(hi asp)"))
        fields.append(ov.get("exp_int", "(exp_int asp)"))
        return f"(Str.Asp {' '.join(fields)})"

    # ===================================================================
    # Str.Sem
    # ===================================================================
    sc = []  # str cases

    # Constants
    for i, c in enumerate(constants):
        clo, chi = positions[c]
        sc.append(
            f"     ((str.c{i})\n"
            f"      (and (= (lo asp) {clo}) (= (hi asp) {chi})))")

    # Args — positions come from per-model 0-ary interp-fun
    for i in range(n_args):
        sc.append(
            f"     ((str.arg{i})\n"
            f"      (and (= (lo asp) (arg{i}_lo)) (= (hi asp) (arg{i}_hi))))")

    # str.++
    sc.append(
        f"     ((str.++ x y)\n"
        f"      (exists ((mid (int-range (lo asp) (hi asp))))\n"
        f"        (and (Str.Sem x {asp(hi='mid')})\n"
        f"             (Str.Sem y {asp(lo='mid')}))))")

    # str.at  — single character extraction
    sc.append(
        f"     ((str.at x i)\n"
        f"      (and (= (hi asp) (+ (lo asp) 1))\n"
        f"           (exists ((slo (int-range 0 {tape_len})))\n"
        f"             (exists ((shi (int-range slo {tape_len})))\n"
        f"               (exists ((k (univ (SymInt (model asp)))))\n"
        f"                 (and (Str.Sem x {asp(lo='slo', hi='shi')})\n"
        f"                      (Int.Sem i {asp(lo='slo', hi='shi', exp_int='k')})\n"
        f"                      (not (= k bot))\n"
        f"                      (char_eq (pos_offset slo k) (lo asp))))))))")

    # str.substr
    sc.append(
        f"     ((str.substr x i len)\n"
        f"      (exists ((slo (int-range 0 {tape_len})))\n"
        f"        (exists ((shi (int-range slo {tape_len})))\n"
        f"          (exists ((k (univ (SymInt (model asp)))))\n"
        f"            (and (Str.Sem x {asp(lo='slo', hi='shi')})\n"
        f"                 (Int.Sem i {asp(lo='slo', hi='shi', exp_int='k')})\n"
        f"                 (not (= k bot))\n"
        f"                 (Int.Sem len {asp(lo='slo', hi='shi', exp_int='(pos_diff (hi asp) (lo asp))')})\n"
        f"                 (substr_match (pos_offset slo k) (lo asp) (pos_diff (hi asp) (lo asp))))))))")

    # str.replace — first-occurrence replacement
    # replace(x, y, z) matching [lo, hi):
    #   exists (xlo, xhi, ylo, yhi, zlo, zhi, k):
    #     Str.Sem(x, xlo, xhi) AND Str.Sem(y, ylo, yhi) AND
    #     k >= 0 AND k + len(y) <= len(x) AND
    #     substr_match(ylo, pos_offset(xlo, k), len(y))   -- y appears at position k in x
    #     -- no earlier occurrence: forall j in [0, k-1]: not substr_match(...)
    #     -- output = x[0..k] ++ z ++ x[k+len(y)..]
    #     -- which must equal tape[lo..hi]
    #     -- i.e., exists (mid1, mid2):
    #       substr_match(xlo, lo, k) AND Str.Sem(z, mid1, mid2) AND
    #       substr_match(pos_offset(xlo, int_plus(k, pos_diff(yhi, ylo))), mid2,
    #                    int_minus(pos_diff(xhi, xlo), int_plus(k, pos_diff(yhi, ylo))))
    # This is complex. Let me write it as a single nested expression.
    sc.append(
        f"     ((str.replace x y z)\n"
        f"      (exists ((xlo (int-range 0 {tape_len})))\n"
        f"        (exists ((xhi (int-range xlo {tape_len})))\n"
        f"          (exists ((ylo (int-range 0 {tape_len})))\n"
        f"            (exists ((yhi (int-range ylo {tape_len})))\n"
        f"              (exists ((k (univ (SymInt (model asp)))))\n"
        f"                (and (Str.Sem x {asp(lo='xlo', hi='xhi')})\n"
        f"                     (Str.Sem y {asp(lo='ylo', hi='yhi')})\n"
        f"                     (not (= k bot))\n"
        f"                     (substr_match ylo (pos_offset xlo k) (pos_diff yhi ylo))\n"
        f"                     (forall ((j (univ (SymInt (model asp)))))\n"
        f"                       (or (= j bot) (= j k)\n"
        f"                           (= (int_minus j $0) bot)\n"
        f"                           (= (int_minus k (int_plus j $1)) bot)\n"
        f"                           (not (substr_match ylo (pos_offset xlo j) (pos_diff yhi ylo)))))\n"
        f"                     (exists ((mid (int-range (lo asp) (hi asp))))\n"
        f"                       (exists ((mid2 (int-range mid (hi asp))))\n"
        f"                         (and (substr_match xlo (lo asp) k)\n"
        f"                              (Str.Sem z {asp(lo='mid', hi='mid2')})\n"
        f"                              (substr_match (pos_offset xlo (int_plus k (pos_diff yhi ylo))) mid2\n"
        f"                                            (int_minus (pos_diff xhi xlo) (int_plus k (pos_diff yhi ylo))))\n"
        f"                              (= (pos_diff mid (lo asp)) k)\n"
        f"                              (= (pos_diff (hi asp) mid2)\n"
        f"                                 (int_minus (pos_diff xhi xlo) (int_plus k (pos_diff yhi ylo))))))))))))))")

    # str.ite
    sc.append(
        f"     ((str.ite b x y)\n"
        f"      (or (and (Bool.Sem b asp) (Str.Sem x asp))\n"
        f"          (and (not (Bool.Sem b asp)) (Str.Sem y asp))))")

    # str.int2str — convert int to its digit string
    int2str_cases = []
    for v in range(0, min(max_int + 1, 100)):
        ds = str(v)
        if ds in positions:
            dlo, dhi = positions[ds]
            int2str_cases.append(
                f"(and (Int.Sem i {asp(exp_int=f'${v}')}) (= (lo asp) {dlo}) (= (hi asp) {dhi}))")
    if int2str_cases:
        sc.append(
            f"     ((str.int2str i)\n"
            f"      (or {'           '.join(int2str_cases)}))")
    else:
        sc.append("     ((str.int2str i) false)")

    out.append("(define-semantics")
    out.append("  ((Str.Sem (e Str) (asp Str.Asp)))")
    out.append("  ((match e")
    out.append("\n".join(sc))
    out.append("  )))")
    out.append("")

    # ===================================================================
    # Int.Sem
    # ===================================================================
    ic = []

    ic.append("     ((int.0) (= (exp_int asp) $0))")
    ic.append("     ((int.1) (= (exp_int asp) $1))")
    ic.append("     ((int.neg1) (= (exp_int asp) $neg1))")

    # int.+
    ic.append(
        f"     ((int.+ x y)\n"
        f"      (exists ((a (univ (SymInt (model asp)))))\n"
        f"        (exists ((b (univ (SymInt (model asp)))))\n"
        f"          (and (Int.Sem x {asp(exp_int='a')})\n"
        f"               (Int.Sem y {asp(exp_int='b')})\n"
        f"               (= (exp_int asp) (int_plus a b))))))")

    # int.-
    ic.append(
        f"     ((int.- x y)\n"
        f"      (exists ((a (univ (SymInt (model asp)))))\n"
        f"        (exists ((b (univ (SymInt (model asp)))))\n"
        f"          (and (Int.Sem x {asp(exp_int='a')})\n"
        f"               (Int.Sem y {asp(exp_int='b')})\n"
        f"               (= (exp_int asp) (int_minus a b))))))")

    # int.len
    ic.append(
        f"     ((int.len x)\n"
        f"      (exists ((slo (int-range 0 {tape_len})))\n"
        f"        (exists ((shi (int-range slo {tape_len})))\n"
        f"          (and (Str.Sem x {asp(lo='slo', hi='shi')})\n"
        f"               (= (exp_int asp) (pos_diff shi slo))))))")

    # int.to_int — precomputed for small digit strings
    to_int_cases = []
    for v in range(0, min(max_int + 1, 100)):
        ds = str(v)
        if ds in positions:
            dlo, dhi = positions[ds]
            to_int_cases.append(
                f"(and (Str.Sem x {asp(lo=str(dlo), hi=str(dhi))}) (= (exp_int asp) ${v}))")
    if to_int_cases:
        ic.append(
            f"     ((int.to_int x)\n"
            f"      (or {'          '.join(to_int_cases)}))")
    else:
        ic.append("     ((int.to_int x) false)")

    # int.ite
    ic.append(
        f"     ((int.ite b x y)\n"
        f"      (or (and (Bool.Sem b asp) (Int.Sem x asp))\n"
        f"          (and (not (Bool.Sem b asp)) (Int.Sem y asp))))")

    # int.indexof — find first occurrence of y in x starting at position k
    # Result = exp_int. Express "first match" using forall.
    ic.append(
        f"     ((int.indexof x y k)\n"
        f"      (exists ((xlo (int-range 0 {tape_len})))\n"
        f"        (exists ((xhi (int-range xlo {tape_len})))\n"
        f"          (exists ((ylo (int-range 0 {tape_len})))\n"
        f"            (exists ((yhi (int-range ylo {tape_len})))\n"
        f"              (exists ((kv (univ (SymInt (model asp)))))\n"
        f"                (and (Str.Sem x {asp(lo='xlo', hi='xhi')})\n"
        f"                     (Str.Sem y {asp(lo='ylo', hi='yhi')})\n"
        f"                     (Int.Sem k {asp(exp_int='kv')})\n"
        f"                     (not (= kv bot))\n"
        f"                     (or\n"
        f"                       (and (not (= (exp_int asp) $neg1))\n"
        f"                            (not (= (exp_int asp) bot))\n"
        f"                            (substr_match ylo (pos_offset xlo (exp_int asp)) (pos_diff yhi ylo))\n"
        f"                            (not (= (int_minus (exp_int asp) kv) bot))\n"
        f"                            (forall ((j (univ (SymInt (model asp)))))\n"
        f"                              (or (= j bot)\n"
        f"                                  (= (int_minus j kv) bot)\n"
        f"                                  (= (int_minus (exp_int asp) (int_plus j $1)) bot)\n"
        f"                                  (not (substr_match ylo (pos_offset xlo j) (pos_diff yhi ylo))))))\n"
        f"                       (and (= (exp_int asp) $neg1)\n"
        f"                            (forall ((j (univ (SymInt (model asp)))))\n"
        f"                              (or (= j bot)\n"
        f"                                  (= (int_minus j kv) bot)\n"
        f"                                  (= (int_minus (pos_diff xhi xlo) (int_plus j (pos_diff yhi ylo))) bot)\n"
        f"                                  (not (substr_match ylo (pos_offset xlo j) (pos_diff yhi ylo))))))))))))))")

    out.append("(define-semantics")
    out.append("  ((Int.Sem (e SInt) (asp Str.Asp)))")
    out.append("  ((match e")
    out.append("\n".join(ic))
    out.append("  )))")
    out.append("")

    # ===================================================================
    # Bool.Sem
    # ===================================================================
    bc = []

    bc.append("     ((bool.true) true)")
    bc.append("     ((bool.false) false)")

    # bool.=
    bc.append(
        f"     ((bool.= x y)\n"
        f"      (exists ((v (univ (SymInt (model asp)))))\n"
        f"        (and (Int.Sem x {asp(exp_int='v')})\n"
        f"             (Int.Sem y {asp(exp_int='v')}))))")

    # bool.prefixof — tape[xlo..xhi] is prefix of tape[ylo..yhi]
    # = substr_match(xlo, ylo, xhi-xlo) AND len(x) <= len(y)
    bc.append(
        f"     ((bool.prefixof x y)\n"
        f"      (exists ((xlo (int-range 0 {tape_len})))\n"
        f"        (exists ((xhi (int-range xlo {tape_len})))\n"
        f"          (exists ((ylo (int-range 0 {tape_len})))\n"
        f"            (exists ((yhi (int-range ylo {tape_len})))\n"
        f"              (and (Str.Sem x {asp(lo='xlo', hi='xhi')})\n"
        f"                   (Str.Sem y {asp(lo='ylo', hi='yhi')})\n"
        f"                   (not (= (int_minus (pos_diff yhi ylo) (pos_diff xhi xlo)) bot))\n"
        f"                   (substr_match xlo ylo (pos_diff xhi xlo))))))))")

    # bool.suffixof — tape[xlo..xhi] is suffix of tape[ylo..yhi]
    # = substr_match(xlo, yhi-(xhi-xlo), xhi-xlo) AND len(x) <= len(y)
    bc.append(
        f"     ((bool.suffixof x y)\n"
        f"      (exists ((xlo (int-range 0 {tape_len})))\n"
        f"        (exists ((xhi (int-range xlo {tape_len})))\n"
        f"          (exists ((ylo (int-range 0 {tape_len})))\n"
        f"            (exists ((yhi (int-range ylo {tape_len})))\n"
        f"              (and (Str.Sem x {asp(lo='xlo', hi='xhi')})\n"
        f"                   (Str.Sem y {asp(lo='ylo', hi='yhi')})\n"
        f"                   (not (= (int_minus (pos_diff yhi ylo) (pos_diff xhi xlo)) bot))\n"
        f"                   (substr_match xlo (pos_offset ylo (int_minus (pos_diff yhi ylo) (pos_diff xhi xlo))) (pos_diff xhi xlo))))))))")

    # bool.contains — str.contains(x, y) = y is a substring of x
    # = exists k: substr_match(ylo, pos_offset(xlo, k), yhi-ylo) AND 0<=k AND k+len(y)<=len(x)
    bc.append(
        f"     ((bool.contains x y)\n"
        f"      (exists ((xlo (int-range 0 {tape_len})))\n"
        f"        (exists ((xhi (int-range xlo {tape_len})))\n"
        f"          (exists ((ylo (int-range 0 {tape_len})))\n"
        f"            (exists ((yhi (int-range ylo {tape_len})))\n"
        f"              (and (Str.Sem x {asp(lo='xlo', hi='xhi')})\n"
        f"                   (Str.Sem y {asp(lo='ylo', hi='yhi')})\n"
        f"                   (exists ((k (univ (SymInt (model asp)))))\n"
        f"                     (and (not (= k bot))\n"
        f"                          (not (= (int_minus k $0) bot))\n"
        f"                          (not (= (int_minus (pos_diff xhi xlo) (int_plus k (pos_diff yhi ylo))) bot))\n"
        f"                          (substr_match ylo (pos_offset xlo k) (pos_diff yhi ylo))))))))))")

    out.append("(define-semantics")
    out.append("  ((Bool.Sem (e SBool) (asp Str.Asp)))")
    out.append("  ((match e")
    out.append("\n".join(bc))
    out.append("  )))")
    out.append("")

    # ===================================================================
    # Models — one per constraint (shared tape tables, varying arg positions)
    # ===================================================================
    pos_elems = " ".join(f"${i}" for i in range(tape_len)) + " $end"
    si_elems = "bot $neg1 " + " ".join(f"${i}" for i in range(max_int + 1))

    # Precompute shared table strings (identical across models)
    shared_tables = []

    # char_eq
    shared_tables.append("  (interp-fun char_eq (match (")
    for p1 in range(tape_len):
        for p2 in range(tape_len):
            if tape[p1] == tape[p2]:
                shared_tables.append(f"    ((${p1} ${p2}) true)")
    shared_tables.append("    ((_ _) false)")
    shared_tables.append("  )))")

    # int_plus
    shared_tables.append("  (interp-fun int_plus (match (")
    for a in range(-1, max_int + 1):
        for b in range(-1, max_int + 1):
            r = a + b
            r_s = si(r) if -1 <= r <= max_int else "bot"
            shared_tables.append(f"    (({si(a)} {si(b)}) {r_s})")
    for v in range(-1, max_int + 1):
        shared_tables.append(f"    (({si(v)} bot) bot)")
        shared_tables.append(f"    ((bot {si(v)}) bot)")
    shared_tables.append("    ((bot bot) bot)")
    shared_tables.append("  )))")

    # int_minus
    shared_tables.append("  (interp-fun int_minus (match (")
    for a in range(-1, max_int + 1):
        for b in range(-1, max_int + 1):
            r = a - b
            r_s = si(r) if -1 <= r <= max_int else "bot"
            shared_tables.append(f"    (({si(a)} {si(b)}) {r_s})")
    for v in range(-1, max_int + 1):
        shared_tables.append(f"    (({si(v)} bot) bot)")
        shared_tables.append(f"    ((bot {si(v)}) bot)")
    shared_tables.append("    ((bot bot) bot)")
    shared_tables.append("  )))")

    # pos_offset
    shared_tables.append("  (interp-fun pos_offset (match (")
    for p in range(tape_len + 1):
        p_s = pos_name(p, tape_len)
        for i in range(-1, max_int + 1):
            r = p + i
            r_s = pos_name(r, tape_len) if 0 <= r <= tape_len else "$end"
            shared_tables.append(f"    (({p_s} {si(i)}) {r_s})")
        shared_tables.append(f"    (({p_s} bot) $end)")
    shared_tables.append("  )))")

    # pos_diff
    shared_tables.append("  (interp-fun pos_diff (match (")
    for p1 in range(tape_len + 1):
        p1_s = pos_name(p1, tape_len)
        for p2 in range(tape_len + 1):
            p2_s = pos_name(p2, tape_len)
            r = p1 - p2
            r_s = si(r) if 0 <= r <= max_int else "bot"
            shared_tables.append(f"    (({p1_s} {p2_s}) {r_s})")
    shared_tables.append("  )))")

    # substr_match
    shared_tables.append("  (interp-fun substr_match (match (")
    for n in range(0, max_int + 1):
        for p1 in range(tape_len + 1):
            for p2 in range(tape_len + 1):
                if p1 + n <= tape_len and p2 + n <= tape_len:
                    if tape[p1:p1+n] == tape[p2:p2+n]:
                        shared_tables.append(f"    (({pos_name(p1, tape_len)} {pos_name(p2, tape_len)} {si(n)}) true)")
    shared_tables.append("    ((_ _ _) false)")
    shared_tables.append("  )))")

    shared_tables_str = "\n".join(shared_tables)

    # Emit one model per constraint
    for ci, (inputs, output) in enumerate(constraints):
        out.append(f"(define-model m{ci}")
        out.append(f"  (define-univ Pos ({pos_elems}))")
        out.append(f"  (define-univ SymInt ({si_elems}))")
        # Per-model 0-ary arg position functions
        for ai, inp in enumerate(inputs):
            ilo, ihi = positions[inp]
            out.append(f"  (interp-fun arg{ai}_lo (${ilo}))")
            out.append(f"  (interp-fun arg{ai}_hi (${ihi}))")
        out.append(shared_tables_str)
        out.append(")")
        out.append("")

    # --- Synth-fun ---
    out.append("(synth-fun phi () Str)")
    out.append("")

    # --- Constraints --- one per model
    for ci, (inputs, output) in enumerate(constraints):
        out_lo, out_hi = positions[output]
        out.append(
            f"(constraint (Str.Sem phi (Str.Asp m{ci} {out_lo} {out_hi} $0)))")

    out.append("")
    out.append("(check-synth)")

    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description="Convert SyGuS SLIA to Delis .sl")
    ap.add_argument("--input", required=True, help="Input SyGuS SLIA file")
    ap.add_argument("--output", required=True, help="Output Delis .sl file")
    args = ap.parse_args()

    path = Path(args.input)
    n_args, constants, constraints = parse_sygus(path)

    if not constraints:
        print(f"warning: no constraints in {path}", file=sys.stderr)
        return

    tape, positions = build_tape(n_args, constants, constraints)
    max_int = max(len(s) for s in positions)

    print(f"{path.name}: {n_args} args, {len(constants)} consts, "
          f"{len(constraints)} constraints, tape={len(tape)}, max_int={max_int}")

    text = emit(n_args, constants, constraints, tape, positions, max_int)
    Path(args.output).write_text(text)
    print(f"  wrote {args.output}")


if __name__ == "__main__":
    main()
